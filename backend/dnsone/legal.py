"""Court-ordered blocking: names a court or regulator ordered blocked, kept apart from ad-blocking.

The list (legal_blocks) is its own RPZ zone, loaded before every other one, so it wins over allow
rules and allowlists, applies to every client group (also groups with blocking off) and stays on
while ad-blocking is paused. A name is answered with the address of the legal notice page
(Settings → Court orders) or, without one, NXDOMAIN; either carries Extended DNS Error 16
"Censored" (RFC 8914: blocked because of an external requirement). Entries are never deleted, only
lifted with a reason, and every change is in the audit log.

The notice page: nginx answers HTTP on the page's address (deploy/nginx/dnsone-legal.conf) with
/api/legal/notice, which names the order that covers the requested host. HTTPS cannot show it
(the certificate cannot match the blocked name); browsers show a connection error instead.
"""

from __future__ import annotations

import html
import ipaddress
from datetime import date

from sqlalchemy import select
from sqlalchemy.orm import Session

from . import validation
from .models import LegalBlock, Setting

PAGE_KEY = "legal.page"
POLICY = "dnsone-legal"
# RFC 8914: 16 Censored. Ad-blocking uses 15 Blocked.
EDE = 16
DEFAULT_PAGE = {
    "address4": "", "address6": "",
    "title": "Access to this site is blocked",
    "message": "Access to this website has been blocked by order of a competent authority. This is not a technical fault.",
    "show_reference": True,
}


def get_page(db: Session) -> dict:
    row = db.get(Setting, PAGE_KEY)
    return {**DEFAULT_PAGE, **(row.value if row else {})}


def set_page(db: Session, data: dict) -> dict:
    out = dict(DEFAULT_PAGE)
    for key, version in (("address4", 4), ("address6", 6)):
        raw = str(data.get(key) or "").strip()
        if raw:
            try:
                address = ipaddress.ip_address(raw)
            except ValueError:
                raise validation.ValidationError(key, f"Enter an IPv{version} address.") from None
            if address.version != version:
                raise validation.ValidationError(key, f"Enter an IPv{version} address.")
            out[key] = str(address)
    for key, limit in (("title", 200), ("message", 2000)):
        text = str(data.get(key) or "").strip()
        if not text:
            raise validation.ValidationError(key, "Enter the text the page shows.")
        out[key] = text[:limit]
    out["show_reference"] = bool(data.get("show_reference", True))
    row = db.get(Setting, PAGE_KEY)
    if row is None:
        db.add(Setting(name=PAGE_KEY, value=out))
    else:
        row.value = out
    return out


def active(db: Session) -> list[LegalBlock]:
    return list(db.scalars(select(LegalBlock).where(LegalBlock.active.is_(True)).order_by(LegalBlock.pattern)))


def triggers(blocks: list[LegalBlock]) -> list[str]:
    """RPZ triggers: a name covers itself and every name below it; *.name only the names below."""
    out: set[str] = set()
    for b in blocks:
        out.add(b.pattern)
        if not b.pattern.startswith("*."):
            out.add(f"*.{b.pattern}")
    return sorted(out, key=lambda p: p.split(".")[::-1])


def render(db: Session, zone: str, serial: int) -> tuple[str, int]:
    page = get_page(db)
    answer = [f"A\t{page['address4']}"] if page["address4"] else []
    answer += [f"AAAA\t{page['address6']}"] if page["address6"] else []
    if not answer:
        answer = ["CNAME\t."]
    names = triggers(active(db))
    lines = [
        "; Generated by DNSOne from the court-ordered blocking list. Do not edit.",
        f"; {len(names)} triggers",
        "$TTL 60",
        f"@\tIN\tSOA\tlocalhost. hostmaster.localhost. {serial} 3600 600 86400 60",
        "@\tIN\tNS\tlocalhost.",
    ]
    for name in names:
        lines += [f"{name}\t{rd}" for rd in answer]
    return "\n".join(lines) + "\n", len(names)


def covering(db: Session, host: str) -> LegalBlock | None:
    """The active entry that blocks `host` (exact name, then the closest parent)."""
    host = host.strip().lower().rstrip(".").split(":")[0]
    if not host:
        return None
    labels = host.split(".")
    candidates = [host] + [f"*.{'.'.join(labels[i:])}" for i in range(1, len(labels))] + [".".join(labels[i:]) for i in range(1, len(labels))]
    rows = {b.pattern: b for b in db.scalars(select(LegalBlock).where(LegalBlock.active.is_(True), LegalBlock.pattern.in_(candidates)))}
    for i in range(len(labels)):
        name = ".".join(labels[i:])
        if i == 0 and name in rows:
            return rows[name]
        if i > 0 and (f"*.{name}" in rows or name in rows):
            return rows.get(f"*.{name}") or rows[name]
    return None


def notice_html(db: Session, host: str) -> str:
    page = get_page(db)
    block = covering(db, host)
    esc = html.escape
    details = ""
    if block is not None and page["show_reference"]:
        when = f" of {block.ordered_on:%d %B %Y}" if isinstance(block.ordered_on, date) else ""
        details = (f"<dl><dt>Site</dt><dd>{esc(host)}</dd><dt>Ordered by</dt><dd>{esc(block.authority)}</dd>"
                   f"<dt>Reference</dt><dd>{esc(block.reference)}{esc(when)}</dd></dl>")
    message = "".join(f"<p>{esc(p)}</p>" for p in page["message"].split("\n") if p.strip())
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex"><title>{esc(page['title'])}</title>
<style>
:root {{ color-scheme: light dark; }}
body {{ margin: 0; font: 16px/1.55 system-ui, -apple-system, "Segoe UI", sans-serif; background: #f4f7f7; color: #14302f; }}
main {{ max-width: 640px; margin: 12vh auto; padding: 32px 28px; background: #fff; border-radius: 14px; border-top: 6px solid #0d7f78; box-shadow: 0 8px 30px rgba(0,0,0,.08); }}
h1 {{ font-size: 1.5rem; margin: 0 0 16px; }}
dl {{ display: grid; grid-template-columns: max-content 1fr; gap: 6px 16px; margin: 24px 0 0; padding-top: 16px; border-top: 1px solid #dfe7e7; }}
dt {{ color: #5b7270; }} dd {{ margin: 0; word-break: break-word; }}
@media (prefers-color-scheme: dark) {{ body {{ background: #0e1918; color: #e3eeed; }} main {{ background: #162423; box-shadow: none; }} dl {{ border-color: #2b3d3c; }} dt {{ color: #93aaa8; }} }}
@media (max-width: 700px) {{ main {{ margin: 0; border-radius: 0; min-height: 100vh; box-sizing: border-box; }} }}
</style></head>
<body><main><h1>{esc(page['title'])}</h1>{message}{details}</main></body></html>
"""
